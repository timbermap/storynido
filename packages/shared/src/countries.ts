/** Países con configuración propia (moneda local). */
export const CONFIGURED_COUNTRIES = Object.keys(COUNTRY_DEFAULTS) as CountryCode[];

/** Valores de un país: los propios o, para el resto del mundo, dólares y su idioma. */
export function countryDefaults(code: CountryCode): CountryDefaults {
  return (
    COUNTRY_DEFAULTS[code] ?? {
      code,
      currency: 'USD',
      defaultLocale: languageOfCountry(code),
      launchPhase: 4,
    }
  );
}
